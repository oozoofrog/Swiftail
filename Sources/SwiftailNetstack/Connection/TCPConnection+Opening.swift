import SwiftailBase

/// Connection establishment, including active and passive opens, SYN-SENT segment processing (RFC 9293 §§3.5 and
/// 3.10.7.3), and negotiation of MSS and window scaling.
extension TCPConnection {
    /// Performs an active open. Sends SYN (MSS, SACK-Permitted, Window Scale) and enters SYN-SENT (contract behavior T3).
    ///
    /// - Parameters:
    ///   - local: The local address and port. The stack chooses a local address in the destination's family and
    ///     a free port (contract behavior S8).
    ///   - remote: The peer address and port.
    ///   - initialSequenceNumber: ISS (RFC 6528, generated by the stack).
    ///   - now: The current time.
    /// - Returns: The connection and the outgoing SYN.
    package static func connect(
        from local: IPEndpoint,
        to remote: IPEndpoint,
        initialSequenceNumber: SequenceNumber,
        at now: ContinuousClock.Instant
    ) -> (connection: TCPConnection, outputs: [Output]) {
        var connection = TCPConnection(
            state: .synSent, local: local, remote: remote,
            initialSendSequence: initialSequenceNumber, initialReceiveSequence: SequenceNumber(0),
            offersWindowScale: true, at: now)
        connection.timers[.retransmission] = now + connection.retransmissionTimeout
        return (connection, [.segment(connection.synchronizeSegment())])
    }

    /// Performs a passive open. When the stack passes in a SYN received by the listener, sends SYN-ACK and enters
    /// SYN-RECEIVED (RFC 9293 §3.10.7.2, contract behavior T4).
    ///
    /// Ignores data and FIN carried in the SYN. The peer retransmits them after establishment because they were not
    /// acknowledged. Uses the SYN destination as the local address.
    ///
    /// - Parameters:
    ///   - syn: A SYN without ACK or RST.
    ///   - initialSequenceNumber: ISS.
    ///   - receiveWindowLimit: The receive window cap. The stack keeps it small until the application accepts the
    ///     connection (`unacceptedReceiveWindow`).
    ///   - now: The current time.
    /// - Returns: The connection and the outgoing SYN-ACK.
    /// - Throws: `AcceptError`. If the peer's MSS is below 64, includes the RST to send in response to the SYN (contract behavior X9).
    package static func accept(
        _ syn: TCPSegment,
        initialSequenceNumber: SequenceNumber,
        receiveWindowLimit: Int = ReceiveBuffer.defaultCapacity,
        at now: ContinuousClock.Instant
    ) throws(AcceptError) -> (connection: TCPConnection, outputs: [Output]) {
        guard syn.flags.contains(.syn), !syn.flags.contains(.ack), !syn.flags.contains(.rst) else {
            throw .notInitialSYN
        }
        guard let peerSize = acceptablePeerSegmentSize(syn) else {
            // RFC 9293 §3.10.7.1 sends <SEQ=0><ACK=SEG.SEQ+SEG.LEN><CTL=RST,ACK> for a segment without ACK.
            throw .unacceptableMaximumSegmentSize(
                reset: TCPSegment(
                    source: syn.destination, destination: syn.source, sequenceNumber: SequenceNumber(0),
                    acknowledgmentNumber: syn.sequenceNumber.advanced(by: syn.sequenceLength), flags: [.rst, .ack]))
        }
        var connection = TCPConnection(
            state: .synReceived, local: syn.destination, remote: syn.source,
            initialSendSequence: initialSequenceNumber, initialReceiveSequence: syn.sequenceNumber,
            offersWindowScale: syn.windowScale != nil, receiveWindowLimit: receiveWindowLimit, at: now)
        connection.adoptPeerSynchronize(syn, peerSegmentSize: peerSize)
        connection.timers[.retransmission] = now + connection.retransmissionTimeout
        return (connection, [.segment(connection.synchronizeSegment())])
    }

    /// The local SYN (SYN-SENT) or SYN-ACK (SYN-RECEIVED). Identical on initial send and retransmission. The window is
    /// unscaled (RFC 7323 §2.2), MSS is always included (SHLD-5), and Window Scale is included only when
    /// `offersWindowScale` is true (contract behavior F2). SACK-Permitted is always included in SYN and is included in
    /// SYN-ACK only if the peer's SYN included it (RFC 2018 §2). The RFC leaves the passive-side condition unspecified.
    /// It matches gVisor's SYN-ACK in `connect.go`.
    func synchronizeSegment() -> TCPSegment {
        let acknowledges = state == .synReceived
        return TCPSegment(
            source: localEndpoint, destination: remoteEndpoint, sequenceNumber: initialSendSequence,
            acknowledgmentNumber: acknowledges ? receiveNext : SequenceNumber(0),
            flags: acknowledges ? [.syn, .ack] : [.syn],
            window: UInt16(min(Self.synchronizeWindow, receiveWindowLimit)),
            maximumSegmentSize: UInt16(receiveMaximumSegmentSize),
            windowScale: offersWindowScale ? UInt8(Self.ownWindowShift) : nil,
            sackPermitted: !acknowledges || peerPermitsSACK)
    }

    // MARK: SYN-SENT (RFC 9293 3.10.7.3)

    /// Processes a segment in SYN-SENT in the order given by RFC 9293 §3.10.7.3: ACK check → RST → SYN.
    /// Synchronized states follow §3.10.7.4 (contract behavior T2).
    mutating func receiveInSynSent(_ segment: TCPSegment, at now: ContinuousClock.Instant, into outputs: inout [Output]) {
        let flags = segment.flags
        let ack = segment.acknowledgmentNumber
        // First, ACK. If SEG.ACK =< ISS or SEG.ACK > SND.NXT, replies with RST unless this is an RST, then drops the segment.
        var acknowledgesSynchronize = false
        if flags.contains(.ack) {
            if ack.precedesOrEquals(initialSendSequence) || sendNext.precedes(ack) {
                if !flags.contains(.rst) { outputs.append(.segment(resetSegment(sequence: ack))) }
                return
            }
            acknowledgesSynchronize = sendUnacknowledged.precedes(ack)
        }
        // Second, RST. If the ACK was acceptable, this is refusal (contract behavior T3, “connection reset” in the RFC, refused in gVisor).
        if flags.contains(.rst) {
            if acknowledgesSynchronize { terminate(.refused, into: &outputs) }
            return
        }
        // Fourth, SYN. Drops SYN without ACK (simultaneous open, contract exclusions table). Drops a segment with
        // neither SYN nor RST (step five).
        guard flags.contains(.syn), acknowledgesSynchronize else { return }
        guard let peerSize = Self.acceptablePeerSegmentSize(segment) else {
            outputs.append(.segment(resetSegment(sequence: ack)))
            terminate(.refused, into: &outputs)
            return
        }
        receiveBuffer = ReceiveBuffer(initialSequence: segment.sequenceNumber.advanced(by: 1))
        advertisedWindowEnd = receiveNext.advanced(by: UInt32(Self.synchronizeWindow))
        adoptPeerSynchronize(segment, peerSegmentSize: peerSize)
        sendUnacknowledged = ack
        sendWindowUpdateAcknowledgment = ack
        establish(at: now, into: &outputs)
        // <SEQ=SND.NXT><ACK=RCV.NXT><CTL=ACK>. Piggybacks on any data written. Ignores data and FIN carried in SYN-ACK.
        // The peer retransmits them because they were not acknowledged.
        scheduleAcknowledgment(immediately: true, at: now)
    }

    // MARK: Negotiation

    /// The peer SYN's MSS, or the default if absent. Returns `nil` below 64 (contract behavior X9).
    static func acceptablePeerSegmentSize(_ syn: TCPSegment) -> Int? {
        let size = syn.maximumSegmentSize.map(Int.init) ?? defaultPeerMaximumSegmentSize(for: syn.source.address)
        return size >= minimumPeerSegmentSize ? size : nil
    }

    /// Accepts the MSS, Window Scale, SACK-Permitted, and window from the peer's SYN or SYN-ACK.
    ///
    /// - MSS: `min(peer MSS, MSS for local MTU)` (contract behavior T5). A SACK option on a data segment reduces the
    ///   data by its length (`segmentPayloadLimit`).
    /// - SACK: The local side can send SACK blocks if the peer's SYN included SACK-Permitted (RFC 2018 §4). Negotiated
    ///   separately per direction.
    /// - Window scaling: Enabled only when present on both SYNs. Uses the peer's shift (up to 14) for the send window
    ///   and the local shift for the advertised window (RFC 7323 §2.3).
    /// - Window: The SYN window field is unscaled (RFC 7323 §2.2). SND.WL1 is the SYN sequence number.
    mutating func adoptPeerSynchronize(_ syn: TCPSegment, peerSegmentSize: Int) {
        sendMaximumSegmentSize = min(peerSegmentSize, receiveMaximumSegmentSize)
        peerPermitsSACK = syn.sackPermitted
        statistics.sackPermitted = syn.sackPermitted
        if offersWindowScale, let shift = syn.windowScale {
            sendWindowShift = min(Int(shift), Self.maximumWindowShift)
            receiveWindowShift = Self.ownWindowShift
        }
        sendWindow = Int(syn.window)
        maximumSendWindow = sendWindow
        lastPeerWindow = sendWindow
        sendWindowUpdateSequence = syn.sequenceNumber
    }

    /// Handles establishment for both SYN-SENT and SYN-RECEIVED.
    ///
    /// If SYN was never retransmitted, the handshake RTT is the first sample (Karn, RFC 6298 §3). After a
    /// retransmission, keeps RTO at 3 seconds or more (RFC 6298 §5.7). Creates congestion control here with the actual
    /// MSS, since ACK of SYN does not grow the window (RFC 6928 §2).
    mutating func establish(at now: ContinuousClock.Instant, into outputs: inout [Output]) {
        state = .established
        if retransmissionCount == 0 {
            retransmissionEstimator.recordSample(now - synchronizeSentAt)
        }
        retransmissionEstimator.handshakeCompleted()
        retransmissionCount = 0
        congestionControl = NewRenoCongestionControl(
            maximumSegmentSize: sendMaximumSegmentSize, initialSequenceNumber: initialSendSequence)
        statistics.maximumCongestionWindow = congestionControl.congestionWindow
        timers[.retransmission] = nil
        timers[.keepalive] = now + Self.keepaliveIdle
        outputs.append(.event(.established))
    }
}
